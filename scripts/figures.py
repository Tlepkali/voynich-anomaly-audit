def fig2():
    # scripts/typetoken2.py
    L   = [3, 4, 5, 6, 7]
    tok = [2.03, 4.52, 5.76, 4.50, 3.20]
    typ = [2.48, 2.43, 1.55, 1.98, 1.60]
    s = Svg(560, 300)
    x0, y0, w, h = 62, 62, 420, 175
    s.txt(0, 18, "Slot rigidity: the gap with Latin depends on the unit", 13, INK, weight="600")
    s.txt(0, 34, "excess of glyph–position mutual information over a within-word shuffle, Voynichese ÷ Latin",
          10.5, INK2)
    mx = 6.0
    for v in range(1, 7):
        y = y0 + h - h * (v - 1) / (mx - 1)
