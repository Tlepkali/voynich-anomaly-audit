def fig3():
    # scripts/one_instrument.py, scripts/morf_spread.py
    rows = [("1  affix + vocabulary word", -15.83, None),
            ("2  Goldsmith signatures",     -1.02, None),
            ("3  Morfessor Baseline",      -10.82, (-11.26, -10.18))]
    s = Svg(560, 330)
    x0, y0, w, gap = 210, 66, 265, 44
    s.txt(0, 18, "One quantity, three decompositions", 13, INK, weight="600")
    s.txt(0, 34, "shift in type-level slot rigidity after stripping affixes (manuscript, ZL3b, length 4)",
          10.5, INK2)
    lo, hi = -18.0, 1.0
    px = lambda v: x0 + w * (v - lo) / (hi - lo)
    for v in (-15, -10, -5, 0):
        s.line(px(v), y0 - 10, px(v), y0 + gap * 3 - 20, INK3 if v == 0 else RULE)
        s.txt(px(v), y0 + gap * 3 - 6, str(v).replace("-", "\u2212"), 9.5, INK3, anchor="middle")
    for i, (lab, v, spread) in enumerate(rows):
        y = y0 + gap * i
        s.txt(x0 - 12, y + 8, lab, 11, INK, anchor="end", font=FONT)
        if spread:
            s.rect(px(spread[0]), y - 3, px(spread[1]) - px(spread[0]), 14, FILL3)
            s.line(px(spread[0]), y - 3, px(spread[0]), y + 11, INK3, 1.2)
            s.line(px(spread[1]), y - 3, px(spread[1]), y + 11, INK3, 1.2)
        s.line(px(0), y + 4, px(v), y + 4, FILL, 2.2)
        s.dot(px(v), y + 4, 4, FILL)
        lbl = f"{v:+.2f}".replace("-", "\u2212")
        # подпись справа от точки, если она у левого края — иначе налезает на имя строки
        if px(v) < x0 + w * 0.25: s.txt(px(v) + 10, y - 6, lbl, 10.5, INK, weight="600")
        else: s.txt(px(v) - 10, y + 8, lbl, 10.5, INK, anchor="end", weight="600")
    s.txt(x0 - 12, y0 + gap * 3 + 16, "spread over five seeds", 9.5, INK3, anchor="end")
    s.rect(x0, y0 + gap * 3 + 6, 24, 12, FILL3)
    s.txt(0, y0 + gap * 3 + 44,
          "Morfessor has no seed of its own; its row is a mean of five runs, and Latin's own shift changes sign between them.",
          10, INK3)
    s.txt(0, y0 + gap * 3 + 58,
          "The spread between algorithms is the finding: no single number should be quoted without the procedure.",
          10, INK3)
    s.save("fig3-three-algorithms", "One quantity, three decompositions")

