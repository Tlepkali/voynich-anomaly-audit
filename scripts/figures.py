    for i, v in enumerate(tok): s.dot(px(i), py(v), 3.5, FILL)
    for i, v in enumerate(typ): s.dot(px(i), py(v), 3.5, INK3)
    s.txt(px(3) + 10, py(tok[3]) - 6, "measured on tokens", 10.5, INK, weight="600")
