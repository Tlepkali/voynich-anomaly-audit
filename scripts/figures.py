def n(key, fallback):
    """число из манифеста, иначе запасное (с предупреждением)"""
    if key in NUM: return NUM[key]
    print(f"  ! {key} нет в манифесте, беру запасное {fallback}", file=sys.stderr)
    return fallback

INK   = "#1a1a1a"
INK2  = "#5a5a5a"
INK3  = "#8a8a8a"
RULE  = "#d0d0d0"
FILL  = "#2b2b2b"      # рукопись
FILL2 = "#9a9a9a"      # языки / первое выравнивание
FILL3 = "#c8c8c8"      # второе выравнивание
FONT  = "Helvetica, Arial, sans-serif"
MONO  = "'DejaVu Sans Mono', Menlo, monospace"

def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))

class Svg:
    def __init__(self, w, h):
        self.w, self.h, self.p = w, h, []
    def txt(self, x, y, s, size=11, fill=INK, anchor="start", weight="normal", font=FONT, dy=0):
        self.p.append(f'<text x="{x:.1f}" y="{y+dy:.1f}" font-family="{font}" font-size="{size}" '
                      f'fill="{fill}" text-anchor="{anchor}" font-weight="{weight}">{esc(s)}</text>')
    def rect(self, x, y, w, h, fill=FILL, op=1.0):
        if w <= 0 or h <= 0: return
        self.p.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="{fill}" opacity="{op}"/>')
    def line(self, x1, y1, x2, y2, stroke=RULE, w=1, dash=None):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.p.append(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
                      f'stroke="{stroke}" stroke-width="{w}"{d}/>')
    def path(self, pts, stroke=FILL, w=1.6, dash=None):
        d = "M " + " L ".join(f"{x:.1f} {y:.1f}" for x, y in pts)
        da = f' stroke-dasharray="{dash}"' if dash else ""
        self.p.append(f'<path d="{d}" fill="none" stroke="{stroke}" stroke-width="{w}"{da}/>')
    def dot(self, x, y, r=3.5, fill=FILL):
        self.p.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="{fill}"/>')
    def save(self, name, title):
        head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" '
                f'viewBox="0 0 {self.w} {self.h}"><title>{esc(title)}</title>'
                f'<rect width="{self.w}" height="{self.h}" fill="#ffffff"/>')
        open(f"{OUT}/{name}.svg", "w", encoding="utf-8").write(head + "".join(self.p) + "</svg>")
        print(f"  {OUT}/{name}.svg")

